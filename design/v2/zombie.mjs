const BODY = { walker, runner, stalker, brute };

/**
 * @param type  walker | runner | stalker | brute
 * @param state roam | chase | dark | mono
 * @param view  side | front | back   (side 는 왼쪽. flip 으로 오른쪽)
 */
export function zombie(type, state, { view = 'side', scale = 1, flip = false } = {}) {
  const t = TYPES[type], v = STATES[state];
  if (!t) throw new Error('알 수 없는 타입: ' + type);
  if (!v) throw new Error('알 수 없는 상태: ' + state);
  if (!BODY[type][view]) throw new Error('알 수 없는 방향: ' + view);

  const p = pal(t, v);
  const uid = `z${t.id}${v.id}${view[0]}${String(scale).replace('.', '')}${flip ? 'f' : ''}`;

  const parts = [];
  if (v.glow) {
    const d = t.disc;
    parts.push(`<ellipse rx="${(29 * d).toFixed(1)}" ry="${(9.5 * d).toFixed(1)}" fill="${v.glow}" opacity="${v.gop}"/>`);
    parts.push(`<ellipse rx="${(14 * d).toFixed(1)}" ry="${(4.6 * d).toFixed(1)}" fill="${v.glow}" opacity="${Math.min(0.7, v.gop * 1.9)}"/>`);
  }

  const filt = v.rim
    ? `<filter id="${uid}" x="-50%" y="-25%" width="200%" height="150%">
         <feDropShadow dx="0" dy="0" stdDeviation="2.6" flood-color="${v.rim}" flood-opacity="0.38"/>
       </filter>` : '';

  const drawn = v.rim
    ? `${filt}<g filter="url(#${uid})">${BODY[type][view](p, v.eye)}</g>`
    : BODY[type][view](p, v.eye);

  parts.push(flip ? `<g transform="scale(-1 1)">${drawn}</g>` : drawn);
  return `<g transform="scale(${scale})">${parts.join('')}</g>`;
}

